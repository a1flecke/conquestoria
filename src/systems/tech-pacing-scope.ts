const bySpec = new Map<string, PacingMetadata['scope']>();
for (const scope of Object.keys(TECH_PACING_SCOPE_BY_GROUP) as Array<PacingMetadata['scope']>) {
  for (const id of TECH_PACING_SCOPE_BY_GROUP[scope]) bySpec.set(id, scope);
}

/** The authored scope for a tech with no `pacing` block, or `undefined` when none is authored (a structural error). */
export function getAuthoredTechPacingScope(techId: string): PacingMetadata['scope'] | undefined {
  return bySpec.get(techId);
}
