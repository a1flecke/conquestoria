import { describe, expect, it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { MAP_DIMENSIONS } from '@/core/game-state';
import { loadGeoMap } from '@/systems/geo-map-loader';
import { computeGeographicStartCapacity } from '@/systems/start-placement-system';
import { GEO_START_CAPACITY } from '@/systems/geo-start-capacity-data';
import { getGeographicStartCapacity, getMaxCivilizationsForSetup } from '@/systems/geo-start-capacity';
import { readGeoMapDataFromDisk } from '../helpers/geo-map-data';

const SCRIPTS = ['earth', 'old-world', 'new-world'] as const;
const SIZES = ['small', 'medium', 'large'] as const;

function measured(): Record<string, Record<string, number>> {
  const result: Record<string, Record<string, number>> = {};
  for (const script of SCRIPTS) {
    const data = readGeoMapDataFromDisk(script);
    result[script] = {};
    for (const size of SIZES) {
      const map = loadGeoMap(data.tiles[size], data.rivers[size], MAP_DIMENSIONS[size], script === 'earth');
      result[script][size] = computeGeographicStartCapacity(map, script, size, MAP_DIMENSIONS[size].maxPlayers);
    }
  }
  return result;
}

describe('geographic start capacity (design 2026-11-25, B2)', () => {
  it('matches what the placer can actually hold (UPDATE_GEO_START_CAPACITY=1 rewrites the table)', () => {
    const actual = measured();
    if (process.env.UPDATE_GEO_START_CAPACITY) {
      const body = JSON.stringify(actual, null, 2).replace(/"([a-z-]+)":/g, (_, key) => (key.includes('-') ? `'${key}':` : `${key}:`));
      writeFileSync(
        resolve(__dirname, '../../src/systems/geo-start-capacity-data.ts'),
        `// GENERATED by tests/systems/geo-start-capacity.test.ts (UPDATE_GEO_START_CAPACITY=1). Do not edit by hand.\n`
        + `// How many separated, livable major-civilization starts each real-world map holds (design 2026-11-25, B2).\n`
        + `export const GEO_START_CAPACITY = ${body} as const;\n`,
      );
    }
    expect(actual).toEqual(GEO_START_CAPACITY);
  }, 120_000);

  it('does not shrink medium and large Earth or Old World below today\'s player limits', () => {
    for (const script of ['earth', 'old-world'] as const) {
      expect(getGeographicStartCapacity(script, 'medium')).toBeGreaterThanOrEqual(MAP_DIMENSIONS.medium.maxPlayers);
      expect(getGeographicStartCapacity(script, 'large')).toBeGreaterThanOrEqual(MAP_DIMENSIONS.large.maxPlayers);
    }
  });

  it('caps setup only for real-world maps in Anywhere placement', () => {
    expect(getMaxCivilizationsForSetup('procedural', 'small', 'balanced')).toBe(MAP_DIMENSIONS.small.maxPlayers);
    expect(getMaxCivilizationsForSetup('earth', 'small', 'historical')).toBe(MAP_DIMENSIONS.small.maxPlayers);
    expect(getMaxCivilizationsForSetup('earth', 'small', 'balanced'))
      .toBe(Math.min(MAP_DIMENSIONS.small.maxPlayers, getGeographicStartCapacity('earth', 'small')));
  });
});
