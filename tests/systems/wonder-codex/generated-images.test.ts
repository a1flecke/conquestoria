import { describe, expect, it } from 'vitest';
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { resolve } from 'node:path';
import { getAllWonderCodexContent } from '@/systems/wonder-codex/content';
import { getImageSource } from '@/systems/wonder-codex/sources';

// #609: every generated codex illustration is a plain, metadata-free JPEG made by scripts/codex-image/codex_image.py, has a
// provenance record whose hashes match the shipped bytes, is registered as an image source, and is the image its wonder shows.

const ROOT = resolve(__dirname, '../../..');
const PROV_DIR = resolve(ROOT, 'design/wonder-codex-images');
const records = readdirSync(PROV_DIR).filter(f => f.endsWith('.provenance.json')).sort()
  .map(f => JSON.parse(readFileSync(resolve(PROV_DIR, f), 'utf8')) as Record<string, any>);

const sha = (buf: Buffer) => createHash('sha256').update(buf).digest('hex');

/** JPEG marker segments before the scan data; APP1+ (EXIF, XMP, ICC, C2PA) must not survive the re-encode. */
function jpegSegments(bytes: Buffer): number[] {
  const markers: number[] = [];
  for (let i = 2; i < bytes.length - 4;) {
    if (bytes[i] !== 0xff) break;
    const marker = bytes[i + 1]!;
    if (marker === 0xda) break;
    markers.push(marker);
    i += 2 + bytes.readUInt16BE(i + 2);
  }
  return markers;
}

describe('generated Legendary Codex illustrations (#609)', () => {
  it('has at least one record, and no shipped generated file lacks one', () => {
    expect(records.length).toBeGreaterThan(0);
    const shipped = new Set(records.map(r => `public/images/wonders/codex/${r.id}.jpg`));
    expect(shipped.size).toBe(records.length);
    for (const record of records) expect(record.file).toBe(`public/images/wonders/codex/${record.id}.jpg`);
  });

  it.each(records.map(r => [r.id as string] as const))('%s: a small, metadata-free 16:9 JPEG that matches its provenance', id => {
    const record = records.find(r => r.id === id)!;
    const path = resolve(ROOT, record.file);
    expect(existsSync(path), `${record.file} is missing`).toBe(true);
    const bytes = readFileSync(path);
    expect(bytes.subarray(0, 3).toString('hex')).toBe('ffd8ff');
    expect(bytes.length).toBeLessThanOrEqual(220 * 1024);
    expect(statSync(path).size).toBe(record.output.bytes);
    expect(sha(bytes)).toBe(record.output.sha256);
    expect(jpegSegments(bytes).filter(m => m >= 0xe1 && m <= 0xef), 'EXIF/XMP/ICC/C2PA segments').toEqual([]);

    expect(record.tool).toBe('scripts/codex-image/codex_image.py');
    expect(record.original.sha256).toMatch(/^[0-9a-f]{64}$/);
    expect(record.original.notRedistributed, 'the downloaded original must never be committed').toBe(true);
    expect(record.original.scan.join(' ')).toContain('decodes cleanly');
    expect(record.original.scan.join(' ')).toContain('no data after the image stream');
  });

  it.each(records.map(r => [r.id as string] as const))('%s: records the prompt, generator, plan and date, and the prompt asks for no text or logos', id => {
    const record = records.find(r => r.id === id)!;
    expect(String(record.prompt).length).toBeGreaterThan(80);
    expect(String(record.prompt).toLowerCase()).toContain('no text');
    expect(String(record.prompt).toLowerCase()).toContain('no logos');
    expect(String(record.generator).length).toBeGreaterThan(3);
    expect(record.generatorUrl).toMatch(/^https:\/\//);
    expect(String(record.plan).length).toBeGreaterThan(3);
    expect(record.generatedOn).toMatch(/^\d{4}-\d{2}-\d{2}$/);
    expect(String(record.licence)).toContain('non-commercial');
    expect(record.origin).toBe('generated-image');
  });

  it.each(records.map(r => [r.id as string] as const))('%s: is a registered image source, shown by exactly its wonders, and credited as generated', id => {
    const record = records.find(r => r.id === id)!;
    const source = getImageSource(record.imageSourceId);
    expect(source, `${record.imageSourceId} is not registered in sources.ts`).toBeTruthy();
    expect(source!.localPath).toBe(`/images/wonders/codex/${id}.jpg`);
    expect(source!.attribution).toMatch(/^Generated by /);
    expect(source!.license).toContain('AI-generated');

    const showing = getAllWonderCodexContent().filter(entry => entry.imageSourceId === record.imageSourceId).map(entry => entry.id).sort();
    expect(showing).toEqual([...record.wonderIds].sort());
  });

  it('the foundry photograph is shown only by the wonder it actually depicts (#609 group 1: foundry)', () => {
    const showing = getAllWonderCodexContent().filter(entry => entry.imageSourceId === 'image-foundry').map(entry => entry.id);
    expect(showing).toEqual(['ironroot-foundry']);
  });

  it('the archive reading-room photograph is no longer a stand-in for any wonder card (#609 group 2: archive)', () => {
    const showing = getAllWonderCodexContent().filter(entry => entry.imageSourceId === 'image-archive').map(entry => entry.id);
    expect(showing).toEqual([]);
  });

  it('the solar-power-plant photograph is no longer a stand-in for any wonder card (#609 group 3: sun-tower)', () => {
    const showing = getAllWonderCodexContent().filter(entry => entry.imageSourceId === 'image-sun-tower').map(entry => entry.id);
    expect(showing).toEqual([]);
  });

  it('the Olympia stadium photograph is gone: no wonder card shows it and it is no longer a registered source (#609 group 4: olympia-stadium)', () => {
    const showing = getAllWonderCodexContent().filter(entry => entry.imageSourceId === 'image-olympia-stadium').map(entry => entry.id);
    expect(showing).toEqual([]);
    expect(getImageSource('image-olympia-stadium')).toBeUndefined();
  });

  it('the shipwreck photograph is shown only by the wonder it actually depicts (#609 group 5: ruins)', () => {
    const showing = getAllWonderCodexContent().filter(entry => entry.imageSourceId === 'image-ruins').map(entry => entry.id);
    expect(showing).toEqual(['sunken_ruins']);
  });

  it('never shows the same generated illustration for two different wonders', () => {
    const seen = new Map<string, string>();
    for (const record of records) {
      for (const wonderId of record.wonderIds as string[]) {
        expect(seen.has(wonderId), `${wonderId} has two generated images`).toBe(false);
        seen.set(wonderId, record.id);
      }
    }
  });
});
